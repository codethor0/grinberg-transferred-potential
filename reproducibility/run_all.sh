#!/bin/sh
set -eu

# Resolve paths from this script so the workflow works from any current directory.
SCRIPT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
ROOT_DIR=$(CDPATH= cd -- "$SCRIPT_DIR/.." && pwd)
PYTHON=${PYTHON:-python}

for tool in "$PYTHON" pandoc xelatex; do
    if ! command -v "$tool" >/dev/null 2>&1; then
        printf 'Required tool not found: %s\n' "$tool" >&2
        exit 2
    fi
done

mkdir -p "$ROOT_DIR/figures" "$ROOT_DIR/manuscript"

printf '%s\n' '[1/5] Running the synthetic null benchmark'
"$PYTHON" "$SCRIPT_DIR/synthetic_null_demo.py" > "$SCRIPT_DIR/simulation_check.txt"

printf '%s\n' '[2/5] Generating the nine base figures and benchmark figure'
"$PYTHON" "$SCRIPT_DIR/make_figures.py"

printf '%s\n' '[3/5] Generating the four refined schematics'
"$PYTHON" "$SCRIPT_DIR/refine_figures.py"

printf '%s\n' '[4/5] Assembling final PNG/PDF figure assets'
for asset in "$SCRIPT_DIR"/generated/base/*; do
    cp "$asset" "$ROOT_DIR/figures/"
done
for asset in "$SCRIPT_DIR"/generated/refined/*; do
    cp "$asset" "$ROOT_DIR/figures/"
done

printf '%s\n' '[5/5] Building the final PDF'
pandoc "$ROOT_DIR/manuscript/Manuscript_Source.md" \
    --from=markdown+tex_math_dollars+autolink_bare_uris \
    --to=latex --standalone --toc --toc-depth=2 \
    --template="$SCRIPT_DIR/manuscript.template" \
    --pdf-engine=xelatex --resource-path="$ROOT_DIR" \
    -V documentclass=article -V papersize=letter -V fontsize=10pt \
    -V geometry:margin=0.78in -V mainfont=Palatino -V sansfont=Helvetica \
    -V colorlinks=true -V linkcolor=black -V toccolor=black -V urlcolor=blue \
    -V cover-image="$ROOT_DIR/cover/brain_cover.png" \
    -o "$ROOT_DIR/manuscript/Grinberg_Transferred_Potential_Research_Paper.pdf"

printf '\nSynthetic benchmark output:\n'
cat "$SCRIPT_DIR/simulation_check.txt"
printf '\nFinal PDF: %s\n' "$ROOT_DIR/manuscript/Grinberg_Transferred_Potential_Research_Paper.pdf"
printf '%s\n' 'The synchronized Word manuscript is not regenerated by this script.'
